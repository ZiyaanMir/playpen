#!/bin/bash
# Submit a full train -> evaluate experiment on Isambard-AI (Slurm, GH200, aarch64).
# RUN THIS, not the train.sh / eval.sh job scripts.
#
#   module load brics/userenv      # gives $PROJECTDIR
#   cd <repo root>
#   experiments/isambard/run_experiment.sh dond
#   EXP_TAG=lp_off EXTRA_TRAIN_ARGS=--no-length-penalty \
#     experiments/isambard/run_experiment.sh dond
#
# Same layout, tags and overrides as the Eddie version -- see
# experiments/README.md. Differences here are Slurm vs Grid Engine, $PROJECTDIR vs
# scratch, and the 24 h walltime cap.

set -euo pipefail

GAME_ARG="${1:-}"
[ -n "$GAME_ARG" ] || {
    echo "usage: $0 <game>   (dond | guesswhat | taboo)" >&2
    echo "       optional env: MODEL EXP_TAG MAX_STEPS EVAL_TASKS EXTRA_TRAIN_ARGS ..." >&2
    exit 2
}

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$(dirname "$HERE")/lib/experiment.sh"

export EXP_CLUSTER=isambard
exp_load_preset "$GAME_ARG"
exp_make_id

if [ -z "${PROJECTDIR:-}" ]; then
    module load brics/userenv 2>/dev/null || true
fi
: "${PROJECTDIR:?unset - run 'module load brics/userenv'}"
: "${USER:?unset}"
export MARSHAL_RUNS="${MARSHAL_RUNS:-$PROJECTDIR/$USER/marshal-runs}"

export EXP_DIR="$MARSHAL_RUNS/$EXP_ID"
exp_layout
mkdir -p "$EXP_DIR" "$TRAIN_BASE" "$EVAL_DIR" "$LOG_DIR"

"$REPO/.venv/bin/python" "$EXP_ROOT_DIR/lib/write_manifest.py" "$EXP_DIR"

# One env file for both jobs -- avoids --export quoting problems with values that
# contain commas or spaces (EVAL_TASKS, EXTRA_TRAIN_ARGS).
ENV_FILE="$EXP_DIR/experiment.env"
{
    echo "# Generated by experiments/isambard/run_experiment.sh at $(date --iso-8601=seconds)."
    echo "# Sourced by train.sh and eval.sh. Edit only to re-run by hand."
    for var in EXP_ID EXP_DIR EXP_TAG EXP_CLUSTER REPO MARSHAL_RUNS PROJECTDIR \
               MODEL GAME MARSHAL_CONFIG \
               NUM_GENERATIONS PER_DEVICE_BATCH GRAD_ACCUM MAX_STEPS SAVE_STEPS \
               LEARNING_RATE KL_BETA MAX_COMPLETION_LENGTH MAX_TURNS GRAD_CKPT \
               VLLM_UTIL VLLM_MAX_MODEL_LEN LP_MAX_LEN LP_COEF EXTRA_TRAIN_ARGS \
               EVAL_TASKS EVAL_BATCH EVAL_BASE EVAL_LIMIT EVAL_EXTRA BASE_EVAL_CACHE VENV_LMEVAL; do
        printf '%s=%q\n' "$var" "${!var-}"
    done
} > "$ENV_FILE"

cd "$REPO"

# --parsable prints just the job id, unlike Grid Engine's prose.
TRAIN_ID="$(sbatch --parsable \
    --job-name="tr_${GAME}_$(basename "$MODEL")" \
    --output="$LOG_DIR/train_${EXP_ID}_%j.out" \
    --error="$LOG_DIR/train_${EXP_ID}_%j.err" \
    --export="ALL,EXP_ENV_FILE=$ENV_FILE" \
    ${TRAIN_SBATCH_OPTS:-} \
    "$HERE/train.sh")"
echo "[submit] training  job $TRAIN_ID"

# afterany, NOT afterok. A 20 h run that hits the walltime exits non-zero but has
# still written checkpoint-150; afterok would silently skip evaluating it. eval.sh
# exits cleanly with a message when there is genuinely nothing to score.
EVAL_ID="$(sbatch --parsable \
    --job-name="ev_${GAME}_$(basename "$MODEL")" \
    --dependency="afterany:$TRAIN_ID" \
    --output="$LOG_DIR/eval_${EXP_ID}_%j.out" \
    --error="$LOG_DIR/eval_${EXP_ID}_%j.err" \
    --export="ALL,EXP_ENV_FILE=$ENV_FILE" \
    ${EVAL_SBATCH_OPTS:-} \
    "$HERE/eval.sh")"
echo "[submit] eval      job $EVAL_ID  (held until $TRAIN_ID finishes)"

cat <<EOF

experiment : $EXP_ID
directory  : $EXP_DIR

  manifest.txt        what this run is          cat $EXP_DIR/manifest.txt
  logs/               job output                tail -f $LOG_DIR/train_${EXP_ID}_$TRAIN_ID.out
  train/              checkpoints (checkpoint-<step>/)
  eval/               lm-eval output per checkpoint
  RESULTS.md          score table               (written when eval finishes)

  squeue --me                 # watch both jobs
  scancel $TRAIN_ID $EVAL_ID  # cancel the experiment

Nothing on Isambard is backed up -- rsync the experiment home when it finishes:
  rsync -avz <host>:$EXP_DIR ./
EOF
